"""Generate platform contracts from DBC files plus a small curated VSS mapping per platform.

What is automated vs. curated:

* curated (``sources/mappings/<platform>.yaml``): which DBC signal is which VSS path. No tool can
  infer that ``HV_BATT_VOLTAGE``, ``BMS_packVoltage`` and ``Pack_Voltage`` are the same thing.
* automated (from the DBC): bit layout, scale, offset, unit, and the conversion of that unit
  to the VSS unit; every VSS path is checked against the pinned VSS release, and plausibility
  bounds come from ``sources/mappings/_bounds.yaml`` unless a mapping overrides them.

    uv run python -m covesa_lakehouse.data_generator.dbc_parser            # (re)write contracts/
    uv run python -m covesa_lakehouse.data_generator.dbc_parser --check    # CI: fail if stale
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path
from typing import Any

import yaml
from pydantic import BaseModel, ConfigDict, Field

from covesa_lakehouse.common import can_codec
from covesa_lakehouse.common.contract import (
    ByteOrder,
    CanLayout,
    Contract,
    Encoding,
    MuxSelector,
    Powertrain,
    SignalSpec,
    SourceInfo,
)
from covesa_lakehouse.common.vss import VssCatalog
from covesa_lakehouse.data_generator.dbc_loader import load_dbc
from covesa_lakehouse.data_generator.fetch_sources import OPENDBC_COMMIT, VSS_RELEASE
from covesa_lakehouse.data_generator.units import conversion_factor, normalize_unit

SOURCES = Path("sources")
CONTRACTS = Path("contracts")
_HEADER = "# GENERATED by covesa_lakehouse.data_generator.dbc_parser from {mapping}. Do not edit.\n"


class SignalMapping(BaseModel):
    model_config = ConfigDict(extra="forbid")
    dbc: str = Field(pattern=r"^\w+\.\w+$")  # MESSAGE.SIGNAL
    vss: str
    source_unit: str | None = None  # override when the DBC unit is missing or ambiguous
    min_val: float | None = None
    max_val: float | None = None
    note: str | None = None


class PlatformMapping(BaseModel):
    model_config = ConfigDict(extra="forbid")
    platform_id: str
    platform_name: str
    powertrain: Powertrain
    encoding: Encoding
    dbc: str
    hardware_revs: list[str]
    version: str = "1.0.0"
    signals: list[SignalMapping]


class MappingError(ValueError):
    pass


def _sig(value: float) -> float:
    """Trim float noise introduced by unit conversion (e.g. 0.0062 * 1.609344)."""
    return float(f"{value:.12g}")


def build_contract(
    mapping: PlatformMapping,
    dbc_root: Path,
    vss: VssCatalog,
    bounds: dict[str, dict[str, float]],
) -> Contract:
    db, _ = load_dbc(dbc_root / mapping.dbc)
    errors: list[str] = []
    signals: dict[str, SignalSpec] = {}

    for m in mapping.signals:
        where = f"{mapping.platform_id} {m.dbc}"
        msg_name, sig_name = m.dbc.split(".")
        try:
            message = db.get_message_by_name(msg_name)
        except KeyError:
            close = difflib.get_close_matches(msg_name, [x.name for x in db.messages], 3)
            errors.append(f"{where}: no message {msg_name!r} in {mapping.dbc} (close: {close})")
            continue
        try:
            signal = message.get_signal_by_name(sig_name)
        except KeyError:
            close = difflib.get_close_matches(sig_name, [s.name for s in message.signals], 3)
            errors.append(f"{where}: no signal {sig_name!r} in {msg_name} (close: {close})")
            continue
        byte_order: ByteOrder = (
            "little_endian" if signal.byte_order == "little_endian" else "big_endian"
        )
        mux = None
        if signal.multiplexer_ids:
            selectors = [s for s in message.signals if s.is_multiplexer]
            if (
                len(signal.multiplexer_ids) != 1
                or len(selectors) != 1
                or selectors[0].multiplexer_ids
            ):
                errors.append(
                    f"{where}: only simple (single, non-nested) multiplexing is supported"
                )
                continue
            sel = selectors[0]
            mux = MuxSelector(
                signal=sel.name,
                start_bit=sel.start,
                length=sel.length,
                byte_order="little_endian" if sel.byte_order == "little_endian" else "big_endian",
                value=signal.multiplexer_ids[0],
            )
        try:
            can_codec.extract(
                bytes(message.length), signal.start, signal.length, byte_order, signal.is_signed
            )
        except ValueError as e:
            errors.append(f"{where}: inconsistent DBC layout: {e}")
            continue

        if m.vss not in vss:
            errors.append(f"{where}: {m.vss!r} is not a leaf of VSS {VSS_RELEASE}")
            continue
        vss_unit = vss.leaf(m.vss).unit
        source_unit = m.source_unit or normalize_unit(signal.unit)
        if source_unit is None:
            errors.append(
                f"{where}: unrecognised DBC unit {signal.unit!r}; set source_unit in the mapping"
            )
            continue
        if source_unit == "" and vss_unit:
            errors.append(f"{where}: DBC signal has no unit but VSS expects {vss_unit!r}")
            continue
        try:
            factor = conversion_factor(source_unit, vss_unit)
        except ValueError as e:
            errors.append(f"{where}: {e}")
            continue

        default = bounds.get(m.vss, {})
        lo = m.min_val if m.min_val is not None else default.get("min")
        hi = m.max_val if m.max_val is not None else default.get("max")
        if lo is None or hi is None:
            errors.append(f"{where}: no plausibility bounds for {m.vss} (add to _bounds.yaml)")
            continue
        if signal.name in signals:
            errors.append(f"{where}: signal name {signal.name!r} used twice")
            continue

        signals[signal.name] = SignalSpec(
            vss_path=m.vss,
            scale=_sig(signal.scale * factor),
            offset=_sig(signal.offset * factor),
            unit=vss_unit,
            min_val=float(lo),
            max_val=float(hi),
            note=m.note,
            can=CanLayout(
                message=message.name,
                frame_id=message.frame_id,
                is_extended=message.is_extended_frame,
                dlc=message.length,
                start_bit=signal.start,
                length=signal.length,
                byte_order=byte_order,
                is_signed=signal.is_signed,
                mux=mux,
                dbc_scale=float(signal.scale),
                dbc_offset=float(signal.offset),
                dbc_unit=signal.unit or "",
            ),
        )

    if errors:
        raise MappingError("\n".join(errors))

    synthetic = mapping.dbc.startswith("synthetic/")
    return Contract(
        platform_id=mapping.platform_id,
        platform_name=mapping.platform_name,
        version=mapping.version,
        encoding=mapping.encoding,
        powertrain=mapping.powertrain,
        hardware_revs=mapping.hardware_revs,
        source=SourceInfo(
            dbc=mapping.dbc,
            opendbc_commit=None if synthetic else OPENDBC_COMMIT,
            vss_release=VSS_RELEASE,
            synthetic=synthetic,
        ),
        signals=signals,
    )


def render(contract: Contract, mapping_path: Path) -> str:
    body: dict[str, Any] = contract.model_dump(mode="json", exclude_none=True)
    return _HEADER.format(mapping=mapping_path.as_posix()) + yaml.safe_dump(
        body, sort_keys=False, allow_unicode=True, width=100
    )


def generate(sources: Path = SOURCES, out: Path = CONTRACTS, check: bool = False) -> int:
    vss = VssCatalog.load(sources / "vss" / "vss.json")
    bounds = yaml.safe_load((sources / "mappings" / "_bounds.yaml").read_text(encoding="utf-8"))
    out.mkdir(parents=True, exist_ok=True)
    failures: list[str] = []
    stale: list[str] = []

    for path in sorted((sources / "mappings").glob("[!_]*.yaml")):
        mapping = PlatformMapping.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))
        try:
            contract = build_contract(mapping, sources / "dbc", vss, bounds)
        except MappingError as e:
            failures.append(str(e))
            continue
        target = out / f"{mapping.platform_id.lower()}.yaml"
        text = render(contract, path)
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(target.as_posix())
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
            print(f"{target}  ({len(contract.signals)} signals, {contract.encoding})")

    for failure in failures:
        print(failure, file=sys.stderr)
    for name in stale:
        print(f"stale contract: {name} (re-run dbc_parser)", file=sys.stderr)
    return 1 if failures or stale else 0


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sources", type=Path, default=SOURCES)
    parser.add_argument("--out", type=Path, default=CONTRACTS)
    parser.add_argument("--check", action="store_true", help="fail if contracts/ is out of date")
    args = parser.parse_args()
    sys.exit(generate(args.sources, args.out, args.check))


if __name__ == "__main__":
    main()
